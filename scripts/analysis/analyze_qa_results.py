#!/usr/bin/env python3
"""
Unified QA Analysis Script

Analyzes results generated by run_qa.py (and legacy scripts).

Usage:
  uv run python scripts/analyze_results.py --mode nosearch --model gpt-oss-120b
  uv run python scripts/analyze_results.py --mode specify_paper --model gpt-oss-120b
  uv run python scripts/analyze_results.py --mode search --model gpt-oss-120b --scenario full_text --ordering rater
"""

import argparse
from pathlib import Path
import json
import pandas as pd
import matplotlib.pyplot as plt
import sys

# Paths
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
RESULTS_BASE_DIR = PROJECT_ROOT / "results/qa_unified" # New unified dir
LEGACY_RESULTS_BASE_DIR = PROJECT_ROOT / "results/qa"  # Legacy dir fallback

# Support Data Paths
DATA_SIGNOR_BASE = PROJECT_ROOT / "data/papers/signor"
DATA_SEARCH_BASE = PROJECT_ROOT / "data/papers/qa_search"

def parse_filename_interaction(filename: str):
    """Parse SOURCE_TARGET_INTERACTION from filename."""
    stem = Path(filename).stem.replace('.json', '')
    parts = stem.split('_')
    if len(parts) < 3:
        return None, None, None
    return parts[0], parts[1], "_".join(parts[2:])

def load_results(mode, model, scenario=None, ordering=None):
    """Load results based on mode."""
    results = {'true_positive_edges': [], 'true_negative_edges': []}
    
    # Determine base directory
    # Try Unified first, then Legacy
    # Unified: results/qa_unified/{mode}/{model}...
    
    base_path = RESULTS_BASE_DIR / mode / model
    
    if mode == 'search':
        base_path = base_path / scenario / ordering
    
    # If unified doesn't exist, try legacy paths
    if not base_path.exists():
        print(f"Unified path {base_path} not found. Trying legacy paths...")
        if mode == 'nosearch':
            base_path = LEGACY_RESULTS_BASE_DIR / "nosearch" / model
        elif mode == 'specify_paper':
            base_path = LEGACY_RESULTS_BASE_DIR / "signor_ref" / model
        elif mode == 'search':
            # projects/results/qa_comprehensive/{model}/{scenario}/{ordering}
            base_path = PROJECT_ROOT / "results/qa_comprehensive" / model / scenario / ordering

    if not base_path.exists():
        print(f"Error: Could not find results directory at {base_path}")
        return results

    print(f"Loading results from: {base_path}")

    for edge_type in results.keys():
        # Folder names logic
        # unified/legacy qa.py: 'true_positive_edges'
        # legacy qa_comprehensive: 'true_positive'
        
        folders_to_check = [edge_type] # Default unified/legacy-qa
        if mode == 'search':
            folders_to_check = ["true_positive" if "positive" in edge_type else "true_negative"]
        
        found_dir = None
        for f_name in folders_to_check:
            d = base_path / f_name
            if d.exists():
                found_dir = d
                break
        
        if found_dir:
            for f in found_dir.glob("*.json"):
                try:
                    with open(f, 'r') as jf:
                        data = json.load(jf)
                        data['edge_type'] = edge_type
                        data['filename'] = f.name
                        results[edge_type].append(data)
                except Exception as e:
                    print(f"Error reading {f}: {e}")
        else:
            print(f"Warning: directory for {edge_type} not found in {base_path}")

    return results

def calculate_metrics(df, pred_col='prediction', ground_truth_col='ground_truth'):
    """Calculate standard classification metrics."""
    if len(df) == 0: return {}
    
    predictions = df[pred_col]
    truth = df[ground_truth_col]
    
    # logic: True/False/None
    # NaNs are excluded from TP/TN/FP/FN but counted separately
    
    tp = ((truth == True) & (predictions == True)).sum()
    tn = ((truth == False) & (predictions == False)).sum()
    fp = ((truth == False) & (predictions == True)).sum()
    fn = ((truth == True) & (predictions == False)).sum()
    
    total = len(df)
    total_pos = (truth == True).sum()
    total_neg = (truth == False).sum()
    nan_count = predictions.isna().sum() - (1 if predictions.dtype == object and predictions.isna().any() else 0) # Adjust if needed
    nan_count = predictions.isna().sum()

    accuracy = (tp + tn) / total if total > 0 else 0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0
    recall = tp / total_pos if total_pos > 0 else 0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
    
    # Negative class metrics for Macro F1
    pred_neg = tn + fn
    precision_neg = tn / pred_neg if pred_neg > 0 else 0
    recall_neg = tn / total_neg if total_neg > 0 else 0
    f1_neg = 2 * (precision_neg * recall_neg) / (precision_neg + recall_neg) if (precision_neg + recall_neg) > 0 else 0
    
    macro_f1 = (f1 + f1_neg) / 2
    
    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "macro_f1": macro_f1,
        "tp": int(tp), "tn": int(tn), "fp": int(fp), "fn": int(fn),
        "total": int(total)
    }

def print_metrics(title, m):
    print(f"\n{title}")
    print(f"  Acc: {m['accuracy']:.3f} | F1: {m['f1']:.3f} | Macro F1: {m['macro_f1']:.3f}")
    print(f"  Prec: {m['precision']:.3f} | Rec: {m['recall']:.3f}")
    print(f"  TP: {m['tp']} | TN: {m['tn']} | FP: {m['fp']} | FN: {m['fn']} | N={m['total']}")

# ==============================================================================
# Main Analysis Logic
# ==============================================================================

def analyze(args):
    # 1. Load Results
    results = load_results(args.mode, args.model, args.scenario, args.ordering)
    
    all_data = []
    for edge_type, items in results.items():
        for item in items:
            source, target, ix = parse_filename_interaction(item['filename'])
            base_row = {
                'filename': item['filename'],
                'edge_type': edge_type,
                'ground_truth': (edge_type == 'true_positive_edges'),
                'source': source,
                'target': target
            }
            
            # Extract scenarios based on mode
            if args.mode == 'nosearch':
                # legacy qa.py output structure
                # Unified might use 'scenario_without_search'
                # Check for nested structure or flat
                scen = item.get('scenario_without_search', {})
                base_row['prediction'] = scen.get('prediction')
                all_data.append(base_row)
                
            elif args.mode == 'specify_paper':
                # Has 2 scenarios
                s_abs = item.get('scenario_title_abstract', {})
                s_full = item.get('scenario_title_abstract_fulltext', {})
                
                # specific to specify_paper analysis: we might want separate rows or cols
                # Let's put them in columns for a single row per file
                base_row['prediction_abstract'] = s_abs.get('prediction')
                base_row['prediction_fulltext'] = s_full.get('prediction')
                all_data.append(base_row)

            elif args.mode == 'search':
                # Has 1 scenario determined by args.scenario
                # Structure: item['result']['prediction']
                res = item.get('result', {})
                base_row['prediction'] = res.get('prediction')
                # Add support count
                base_row['support_count'] = item.get('supporting_papers_count', 0)
                all_data.append(base_row)

    df = pd.DataFrame(all_data)
    if df.empty:
        print("No data found.")
        return

    print("="*60)
    print(f"Analysis: Mode={args.mode} | Model={args.model}")
    print("="*60)

    # Calculate Metrics
    if args.mode == 'nosearch':
        m = calculate_metrics(df, pred_col='prediction')
        print_metrics("No Search Results", m)

    elif args.mode == 'specify_paper':
        m_abs = calculate_metrics(df, pred_col='prediction_abstract')
        print_metrics("Scenario: Title + Abstract", m_abs)
        
        m_full = calculate_metrics(df, pred_col='prediction_fulltext')
        print_metrics("Scenario: Title + Abstract + Full Text", m_full)

    elif args.mode == 'search':
        m = calculate_metrics(df, pred_col='prediction')
        print_metrics(f"Search Results ({args.scenario}/{args.ordering})", m)
        
        # Breakdown by support count
        print("\nBreakdown by Support Count:")
        for count in sorted(df['support_count'].unique()):
            sub = df[df['support_count'] == count]
            print(f"  Support Count {count} (N={len(sub)}):")
            if len(sub) > 0:
                m_sub = calculate_metrics(sub, pred_col='prediction')
                print(f"    Acc: {m_sub['accuracy']:.3f} | Macro F1: {m_sub['macro_f1']:.3f}")

    # Save Analysis
    output_dir = PROJECT_ROOT / "results/qa_analysis_unified" / args.mode / args.model
    if args.scenario: output_dir = output_dir / args.scenario
    output_dir.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(output_dir / "analysis_results.csv", index=False)
    print(f"\nSaved analysis to {output_dir}")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", required=True, choices=['nosearch', 'specify_paper', 'search'])
    parser.add_argument("--model", default="gpt-oss-120b")
    # Search args
    parser.add_argument("--scenario", choices=['title_abstract', 'full_text'])
    parser.add_argument("--ordering", choices=['shuffle', 'rater'], default='shuffle')
    
    args = parser.parse_args()
    analyze(args)

if __name__ == "__main__":
    main()
